#include <unistd.h>

void	ft_print_comb2(void)
{
	int		a;
	int		b;
	char	s[5];

	a = 0;
	while (a <= 98)
	{
		b = a + 1;
		while (b <= 99)
		{
			s[0] = a / 10 + '0';
			s[1] = a % 10 + '0';
			s[2] = ' ';
			s[3] = b / 10 + '0';
			s[4] = b % 10 + '0';
			write(1, s, 5);
			if (!(a == 98 && b == 99))
				write(1, ", ", 2);
			b++;
		}
		a++;
	}
}

